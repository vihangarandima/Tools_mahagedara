"""
Download official manufacturer product photos for matched ERP items, convert them
to small WebP files in public/images/products/, and regenerate src/data/productImages.ts.

Usage: python scripts/build_product_images.py <matches.json>
matches.json: [{"sku": "...", "match": {"code": "...", "image": "https://..."} | null}, ...]
Requires: pip install pillow
"""
import io
import json
import os
import sys
import time
import urllib.request

from PIL import Image

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT_DIR = os.path.join(ROOT, 'public', 'images', 'products')
TS_FILE = os.path.join(ROOT, 'src', 'data', 'productImages.ts')
MAX_SIZE = 600


def fetch_webp(url, dest):
    req = urllib.request.Request(url, headers={'User-Agent': 'Mozilla/5.0'})
    im = Image.open(io.BytesIO(urllib.request.urlopen(req, timeout=30).read()))
    im = im.convert('RGBA' if im.mode in ('RGBA', 'LA', 'P') else 'RGB')
    im.thumbnail((MAX_SIZE, MAX_SIZE), Image.LANCZOS)
    im.save(dest, 'WEBP', quality=80, method=6)


def main():
    matches = json.load(open(sys.argv[1], encoding='utf8'))
    os.makedirs(OUT_DIR, exist_ok=True)
    mapping = {}
    for row in matches:
        m = row.get('match')
        if not m:
            continue
        code = m['code']
        dest = os.path.join(OUT_DIR, f'{code}.webp')
        if not os.path.exists(dest):
            try:
                fetch_webp(m['image'], dest)
                time.sleep(0.4)
            except Exception as e:
                print('FAILED', code, e)
                continue
        mapping[row['sku']] = f'/images/products/{code}.webp'

    lines = [
        '// Official manufacturer product photos matched to ERP SKUs (generated by scripts/build_product_images.py)',
        'export const PRODUCT_IMAGES: Record<string, string> = {',
    ]
    lines += [f'  {json.dumps(k)}: {json.dumps(v)},' for k, v in sorted(mapping.items())]
    lines.append('};')
    open(TS_FILE, 'w', encoding='utf8').write('\n'.join(lines) + '\n')
    print(f'{len(mapping)} SKUs mapped')


if __name__ == '__main__':
    main()
